export function buildItems(): SurplusItem[] {
  return seeds.map((seed) => {
    const {
      expiresIn,
      reportedAgo,
      deliveredAgo,
      expiredAgo,
      matchWith,
      matchScore,
      matchAgo,
      pickup,
      expiredReason,
      ...rest
    } = seed;

    const item: SurplusItem = {
      ...rest,
      reportedAt: EPOCH - reportedAgo * 60_000,
      expiresAt: EPOCH + expiresIn * 60_000,
      match: matchWith
        ? {
            recipientId: matchWith,
            confirmedAt: EPOCH - (matchAgo ?? 20) * 60_000,
            score: matchScore ?? 0,
          }
        : null,
      pickup: pickup
        ? {
            method: pickup.method,
            driverId: pickup.driverId,
            scheduledAt: EPOCH - (pickup.agoMinutes ?? 20) * 60_000,
            scheduledFor: EPOCH + (pickup.inMinutes ?? 60) * 60_000,
            pickedUpAt:
              pickup.pickedUpAgo === undefined ? undefined : EPOCH - pickup.pickedUpAgo * 60_000,
            note: pickup.note,
          }
        : null,
      deliveredAt: deliveredAgo === undefined ? undefined : EPOCH - deliveredAgo * 60_000,
      expiredAt: expiredAgo === undefined ? undefined : EPOCH - expiredAgo * 60_000,
      expiredReason,
    };
    return item;
  });
}

